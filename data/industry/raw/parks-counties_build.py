def txt(path):
    s = open(path, encoding="utf-8", errors="ignore").read()
    s = re.sub(r'<(script|style)[\s\S]*?</\1>', '', s)
    s = re.sub(r'<[^>]+>', '|', s)
    s = html.unescape(s)
    return re.sub(r'\|(\s*\|)+', '|', s)

def src(url, title, publisher, period, quote):
    return {"url": url, "title": title, "publisher": publisher, "period": period, "accessed": ACC, "quote": quote}

def num(s): return float(s.replace(",", ""))

