def wsts_rows(path, ncols):
    t = txt(path)
    period = re.search(r'資料期間：[^|]*', t).group(0)
    issued = re.search(r'資料發行日期：[^|]*', t).group(0)
    rows = {}
    for name in ("新竹科學園區", "中部科學園區", "南部科學園區", "總　　計"):
        m = re.search(re.escape(name) + r'\|' + r'(?:[\d,.]+\|){%d}([\d,.]+)\|' % (ncols - 1), t)
        rows[name] = m.group(1)
    # 逐字片段：該表的表頭與四列
    i = t.find("單位：")
    quote = period + "｜" + issued + "｜" + t[i:i + 400].split("竹科備註")[0].strip("|")
    return period, rows, quote

