export function iconSvg(name, label = '', className = '') {
  if (!(name in icons)) throw new Error(`Unknown Taiwan.md icon: ${name}`);
  const safeLabel = label.replace(
    /[&<>"']/g,
    (c) =>
      ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[
        c
      ],
  );
  return `<svg class="twmd-icon${className ? ` ${className}` : ''}" viewBox="0 0 24 24" width="1em" height="1em" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="butt" stroke-linejoin="miter" focusable="false" ${label ? `role="img" aria-label="${safeLabel}"` : 'aria-hidden="true"'}><use href="/icons/taiwan.svg#${name}"/></svg>`;
}

/** 把一段介面字串裡對得到的 emoji 換成行線圖示 SVG（給要傳進瀏覽器端 innerHTML 的 i18n 字串用）。
 * 回傳 HTML；呼叫端要用 innerHTML，不能用 textContent。 */
export function iconizeText(text = '') {
  return Array.from(
    new Intl.Segmenter(undefined, { granularity: 'grapheme' }).segment(text),
    ({ segment }) =>
      emojiIcons[segment] ? iconSvg(emojiIcons[segment]) : segment,
  ).join('');
}
